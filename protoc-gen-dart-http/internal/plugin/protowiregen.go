// protoWireImportPath returns the relative import path from a package's
// index.dart to the shared proto_wire.dart at the output root.
func protoWireImportPath(pkg protoreflect.FullName) string {
	return strings.Replace(transportImportPath(pkg), "transport.dart", "proto_wire.dart", 1)
}

